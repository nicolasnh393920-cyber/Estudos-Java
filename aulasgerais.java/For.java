/*
Aula referente a estruturas de repetição e laços de iteração definidos.

O que aprendi:

- Como funciona a sintaxe do laço 'for': inicialização, condição de parada e incremento/decremento.
- Controle do fluxo de repetição com limites pré-determinados.
- Diferença entre executar um bloco de código repetidas vezes manualmente vs. utilizar um loop automatizado (Muito mais recomendável para tarefas que exijam este tipo de trabalho).
*/

public class For {
    public static void main(String[] args) {
        for (int i = 1; i <= 30; i++) {
            System.out.println("Número: " + i);
        }
    }
}
